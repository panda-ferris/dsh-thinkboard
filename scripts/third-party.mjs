// 生成 THIRD_PARTY_NOTICES.md:列出被打进 client.js 的每个第三方包及其许可证全文。
// MIT 等许可证要求随二进制/打包产物保留版权声明,所以由构建自动生成,而不是手写后忘记更新。
import { build } from 'esbuild'
import { readFile, readdir } from 'node:fs/promises'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

export async function thirdPartyNotices() {
  const r = await build({
    entryPoints: [resolve(root, 'src/client/index.js')], bundle: true, write: false, format: 'cjs', platform: 'browser', jsx: 'transform',
    loader: { '.css': 'text' }, external: ['react', 'react-dom', 'react/jsx-runtime'], define: { 'process.env.NODE_ENV': '"production"' }, metafile: true, logLevel: 'silent',
  })
  const names = new Set()
  for (const f of Object.keys(r.metafile.inputs)) {
    const m = f.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/)
    if (m) names.add(m[1])
  }
  const entries = []
  for (const name of [...names].sort()) {
    const dir = resolve(root, 'node_modules', name)
    const pkg = JSON.parse(await readFile(resolve(dir, 'package.json'), 'utf8'))
    const files = await readdir(dir)
    const licFile = files.find((f) => /^licen[cs]e(\.(md|txt))?$/i.test(f))
    const text = licFile ? (await readFile(resolve(dir, licFile), 'utf8')).trim() : null
    entries.push({ name, version: pkg.version, license: pkg.license ?? 'UNKNOWN', homepage: pkg.homepage ?? pkg.repository?.url ?? '', text })
  }
  const lines = [
    '# Third-party notices',
    '',
    'ThinkBoard bundles the following open-source packages into `client.js`.',
    'Each is used under the license shown. This file is generated by `scripts/third-party.mjs` at build time.',
    '',
    ...entries.map((e) => `- **${e.name}** ${e.version} — ${e.license}`),
    '',
  ]
  for (const e of entries) {
    lines.push('---', '', `## ${e.name} ${e.version}`, '', `License: ${e.license}`, e.homepage ? `Source: ${String(e.homepage).replace(/^git\+/, '')}` : '', '')
    lines.push(e.text ? '```text\n' + e.text + '\n```' : `_No license file shipped in the package; the manifest declares ${e.license}._`, '')
  }
  return { markdown: lines.join('\n'), entries }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { entries } = await thirdPartyNotices()
  console.log(entries.map((e) => `${e.name}@${e.version} ${e.license}${e.text ? '' : '  (无许可证文件)'}`).join('\n'))
}
